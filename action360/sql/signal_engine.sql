-- =====================================================================
-- ACTION360 :: 04 Customer Signal Engine
--   CUSTOMER_FEATURES (DT)  raw behavioural features from structured + unstructured data
--   SIGNAL_DEFINITION       governed catalogue of normalised signals
--   CUSTOMER_SIGNAL   (DT)  long-format normalised signals in [0,1]
--   RISK_MODEL_WEIGHT       configurable weights (no hard-coded scoring in app code)
--   CUSTOMER_RISK     (DT)  churn / payment / service risk + explainable top drivers + AI route
-- Everything here is deterministic. AI only *contributes* (sentiment / intent) via
-- CALL_TRANSCRIPT AI_* columns populated by the cost-aware enrichment task.
-- =====================================================================
USE WAREHOUSE ACTION360_WH;
USE SCHEMA ACTION360_DB.CORE;

-- AI insight store (only populated for customers routed to FULL enrichment)
CREATE TABLE IF NOT EXISTS CUSTOMER_AI_INSIGHT (
  CUSTOMER_ID STRING PRIMARY KEY, CUSTOMER_NEED STRING, KEY_DRIVERS VARIANT, PAIN_POINTS VARIANT,
  LATEST_IMPORTANT_INTERACTION STRING, MODEL STRING, GENERATED_AT TIMESTAMP_NTZ);

-- ---------------------------------------------------------------------
-- CUSTOMER_FEATURES
-- ---------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE CUSTOMER_FEATURES
  TARGET_LAG = 'DOWNSTREAM' WAREHOUSE = ACTION360_WH REFRESH_MODE = FULL
  COMMENT = 'Per-customer behavioural features (structured + transcript-derived)'
AS
WITH cfg AS (SELECT TO_DATE(CONFIG_VALUE) AS AS_OF FROM APP_CONFIG WHERE CONFIG_KEY = 'AS_OF_DATE'),
acc AS (
  SELECT CUSTOMER_ID, COUNT(*) PRODUCT_COUNT, ARRAY_AGG(DISTINCT PRODUCT_CODE) WITHIN GROUP (ORDER BY PRODUCT_CODE) PRODUCTS,
    SUM(OUTSTANDING_BALANCE) TOTAL_OUTSTANDING, SUM(PRINCIPAL_OR_SUM_ASSURED) TOTAL_EXPOSURE_OR_COVER,
    SUM(MONTHLY_INSTALMENT) MONTHLY_OBLIGATION, MIN(RENEWAL_OR_RESET_DATE) NEXT_RENEWAL_DATE,
    MIN_BY(PRODUCT_CODE, RENEWAL_OR_RESET_DATE) NEXT_RENEWAL_PRODUCT,
    MAX(IFF(PRODUCT_CODE = 'HL', 1, 0)) HAS_HL, MAX(IFF(PRODUCT_CODE = 'PL', 1, 0)) HAS_PL, MAX(IFF(PRODUCT_CODE = 'AL', 1, 0)) HAS_AL,
    MAX(IFF(PRODUCT_CODE = 'CC', 1, 0)) HAS_CC, MAX(IFF(PRODUCT_CODE = 'HEALTH', 1, 0)) HAS_HEALTH,
    MAX(IFF(PRODUCT_CODE = 'FAMILY_FLOATER', 1, 0)) HAS_FAMILY_FLOATER, MAX(IFF(PRODUCT_CODE = 'TERM_LIFE', 1, 0)) HAS_TERM_LIFE,
    MAX(IFF(PRODUCT_CODE = 'MOTOR', 1, 0)) HAS_MOTOR, MAX(IFF(PRODUCT_CODE = 'HOME_INS', 1, 0)) HAS_HOME_INS
  FROM FACT_ACCOUNT WHERE STATUS = 'ACTIVE' GROUP BY 1),
pay AS (
  SELECT p.CUSTOMER_ID,
    COUNT_IF(PAYMENT_STATUS IN ('MISSED','PARTIAL') AND DUE_DATE >= DATEADD(month, -6, AS_OF)) MISSED_6M,
    COUNT_IF(PAYMENT_STATUS = 'LATE' AND DUE_DATE >= DATEADD(month, -6, AS_OF)) LATE_6M,
    COALESCE(MAX(IFF(DUE_DATE >= DATEADD(day, -90, AS_OF), DAYS_LATE, NULL)), 0) MAX_DAYS_LATE_90D,
    ROUND(COUNT_IF(PAYMENT_STATUS = 'ON_TIME') / NULLIF(COUNT(*), 0), 3) ON_TIME_RATE_12M,
    SUM(IFF(DUE_DATE >= DATEADD(month, -3, AS_OF), AMOUNT_DUE - AMOUNT_PAID, 0)) OVERDUE_AMOUNT
  FROM FACT_PAYMENT p, cfg GROUP BY 1),
ix AS (
  SELECT i.CUSTOMER_ID, i.INTERACTION_TS, i.TOPIC, i.IS_COMPLAINT, i.RESOLUTION_STATUS, i.CHANNEL,
    COALESCE(t.AI_SENTIMENT_SCORE, i.RULE_SENTIMENT) SENTIMENT, t.AI_INTENT,
    LOWER(COALESCE(t.TRANSCRIPT_TEXT, '') || ' ' || COALESCE(i.NOTE, '')) TXT,
    DATEDIFF(day, i.INTERACTION_TS, cfg.AS_OF) DAYS_AGO
  FROM FACT_INTERACTION i LEFT JOIN CALL_TRANSCRIPT t USING (INTERACTION_ID), cfg),
inter AS (
  SELECT CUSTOMER_ID, COUNT(*) TOTAL_INTERACTIONS, COUNT_IF(DAYS_AGO <= 90) INTERACTIONS_90D,
    COUNT_IF(IS_COMPLAINT AND DAYS_AGO <= 90) COMPLAINTS_90D,
    COUNT_IF(IS_COMPLAINT AND RESOLUTION_STATUS IN ('OPEN','ESCALATED')) UNRESOLVED_COUNT,
    COUNT_IF(NOT IS_COMPLAINT AND RESOLUTION_STATUS = 'OPEN') OPEN_REQUESTS,
    COUNT_IF(RESOLUTION_STATUS = 'ESCALATED') ESCALATED_COUNT,
    COUNT_IF(SENTIMENT <= -0.3 AND DAYS_AGO <= 90) NEGATIVE_INTERACTIONS_90D,
    ROUND(AVG(IFF(DAYS_AGO <= 90, SENTIMENT, NULL)), 3) AVG_SENTIMENT_90D,
    MAX_BY(SENTIMENT, INTERACTION_TS) LATEST_SENTIMENT,
    MAX(INTERACTION_TS) LAST_INTERACTION_TS, MIN(DAYS_AGO) DAYS_SINCE_LAST_INTERACTION,
    MODE(TOPIC) DOMINANT_TOPIC,
    MAX(IFF(DAYS_AGO <= 120 AND (AI_INTENT = 'churn_or_switch_intent' OR TXT ILIKE ANY ('%another bank%','%other bank%','%another insurer%','%balance transfer%','%switch%','%move my%','%move everything%','%cheaper%')), 1, 0)) COMPETITOR_MENTION,
    MAX(IFF(DAYS_AGO <= 180 AND TXT ILIKE ANY ('%baby%','%newborn%','%got married%','%recently married%','%new home%'), 1, 0)) LIFE_EVENT,
    MAX(IFF(DAYS_AGO <= 120 AND (AI_INTENT = 'payment_hardship' OR TXT ILIKE ANY ('%lost my job%','%job loss%','%between jobs%','%money is tight%','%hospital bills%')), 1, 0)) HARDSHIP_MENTION,
    MAX(IFF(DAYS_AGO <= 120 AND (AI_INTENT = 'product_interest_upgrade' OR TXT ILIKE ANY ('%premium%card%','%better travel%','%increase the cover%','%promotion%','%promoted%')), 1, 0)) UPGRADE_INTEREST
  FROM ix GROUP BY 1),
ev AS (
  SELECT e.CUSTOMER_ID,
    MAX(IFF(EVENT_TYPE IN ('FORECLOSURE_ENQUIRY','CANCELLATION_ENQUIRY') AND EVENT_STATUS = 'OPEN', 1, 0)) FORECLOSURE_FLAG,
    MAX(IFF(EVENT_TYPE IN ('RESTRUCTURE_REQUEST','PREMIUM_DEFERRAL_REQUEST') AND EVENT_STATUS = 'OPEN', 1, 0)) RESTRUCTURE_FLAG,
    MAX(IFF(EVENT_TYPE = 'TOPUP_ENQUIRY' AND EVENT_STATUS = 'OPEN', 1, 0)) TOPUP_FLAG,
    MAX(IFF(EVENT_TYPE = 'CLAIM_DELAYED' AND EVENT_STATUS = 'OPEN', 1, 0)) CLAIM_DELAYED_FLAG,
    MAX(IFF(EVENT_TYPE = 'DOCUMENT_PENDING' AND EVENT_STATUS = 'OPEN', 1, 0)) DOC_PENDING_FLAG,
    MAX(IFF(EVENT_TYPE = 'ENDORSEMENT_REQUEST' AND EVENT_STATUS = 'OPEN', 1, 0)) ENDORSEMENT_FLAG,
    MAX(IFF(EVENT_TYPE = 'FEE_DISPUTE' AND EVENT_STATUS = 'OPEN', 1, 0)) FEE_DISPUTE_FLAG,
    COUNT_IF(EVENT_TYPE LIKE 'CLAIM%' AND EVENT_DATE >= DATEADD(month, -12, AS_OF)) CLAIMS_12M
  FROM FACT_CLAIM_OR_LOAN_EVENT e, cfg GROUP BY 1),
tx AS (
  SELECT t.CUSTOMER_ID,
    COUNT_IF(CATEGORY = 'SALARY_CREDIT' AND TXN_DATE >= DATEADD(day, -60, AS_OF)) SALARY_CREDITS_60D,
    COUNT_IF(CATEGORY = 'SALARY_CREDIT' AND TXN_DATE < DATEADD(day, -60, AS_OF)) SALARY_CREDITS_PRIOR,
    SUM(IFF(CATEGORY = 'CARD_SPEND' AND TXN_DATE >= DATEADD(day, -90, AS_OF), AMOUNT, 0)) CARD_SPEND_3M,
    SUM(IFF(CATEGORY = 'CARD_SPEND' AND TXN_DATE < DATEADD(day, -90, AS_OF), AMOUNT, 0)) CARD_SPEND_PREV_3M,
    SUM(IFF(CATEGORY = 'TRANSFER_TO_OTHER_BANK' AND TXN_DATE >= DATEADD(day, -90, AS_OF), AMOUNT, 0)) OUTFLOW_3M,
    SUM(IFF(CATEGORY = 'SALARY_CREDIT' AND TXN_DATE >= DATEADD(day, -90, AS_OF), AMOUNT, 0)) INFLOW_3M
  FROM FACT_TRANSACTION t, cfg GROUP BY 1)
SELECT c.CUSTOMER_ID, c.FULL_NAME, c.SEGMENT, c.INDUSTRY_TYPE, c.AGE, c.CITY, c.TENURE_MONTHS, c.PREFERRED_CHANNEL, c.CREDIT_SCORE, c.MONTHLY_INCOME,
  acc.PRODUCT_COUNT, acc.PRODUCTS, acc.TOTAL_OUTSTANDING, acc.TOTAL_EXPOSURE_OR_COVER, acc.MONTHLY_OBLIGATION,
  acc.NEXT_RENEWAL_DATE, acc.NEXT_RENEWAL_PRODUCT, DATEDIFF(day, cfg.AS_OF, acc.NEXT_RENEWAL_DATE) DAYS_TO_RENEWAL,
  acc.HAS_HL, acc.HAS_PL, acc.HAS_AL, acc.HAS_CC, acc.HAS_HEALTH, acc.HAS_FAMILY_FLOATER, acc.HAS_TERM_LIFE, acc.HAS_MOTOR, acc.HAS_HOME_INS,
  COALESCE(pay.MISSED_6M, 0) MISSED_6M, COALESCE(pay.LATE_6M, 0) LATE_6M, COALESCE(pay.MAX_DAYS_LATE_90D, 0) MAX_DAYS_LATE_90D,
  pay.ON_TIME_RATE_12M, COALESCE(pay.OVERDUE_AMOUNT, 0) OVERDUE_AMOUNT,
  CASE WHEN COALESCE(pay.MISSED_6M, 0) > 0 THEN 'DELINQUENT' WHEN COALESCE(pay.LATE_6M, 0) > 0 THEN 'OCCASIONALLY_LATE' ELSE 'CURRENT' END PAYMENT_STATUS,
  COALESCE(inter.TOTAL_INTERACTIONS, 0) TOTAL_INTERACTIONS, COALESCE(inter.INTERACTIONS_90D, 0) INTERACTIONS_90D,
  COALESCE(inter.COMPLAINTS_90D, 0) COMPLAINTS_90D, COALESCE(inter.UNRESOLVED_COUNT, 0) UNRESOLVED_COUNT, COALESCE(inter.OPEN_REQUESTS, 0) OPEN_REQUESTS,
  COALESCE(inter.ESCALATED_COUNT, 0) ESCALATED_COUNT, COALESCE(inter.NEGATIVE_INTERACTIONS_90D, 0) NEGATIVE_INTERACTIONS_90D,
  inter.AVG_SENTIMENT_90D, inter.LATEST_SENTIMENT, inter.LAST_INTERACTION_TS, inter.DAYS_SINCE_LAST_INTERACTION, inter.DOMINANT_TOPIC,
  COALESCE(inter.COMPETITOR_MENTION, 0) COMPETITOR_MENTION, COALESCE(inter.LIFE_EVENT, 0) LIFE_EVENT,
  COALESCE(inter.HARDSHIP_MENTION, 0) HARDSHIP_MENTION, COALESCE(inter.UPGRADE_INTEREST, 0) UPGRADE_INTEREST,
  COALESCE(ev.FORECLOSURE_FLAG, 0) FORECLOSURE_FLAG, COALESCE(ev.RESTRUCTURE_FLAG, 0) RESTRUCTURE_FLAG, COALESCE(ev.TOPUP_FLAG, 0) TOPUP_FLAG,
  COALESCE(ev.CLAIM_DELAYED_FLAG, 0) CLAIM_DELAYED_FLAG, COALESCE(ev.DOC_PENDING_FLAG, 0) DOC_PENDING_FLAG,
  COALESCE(ev.ENDORSEMENT_FLAG, 0) ENDORSEMENT_FLAG, COALESCE(ev.FEE_DISPUTE_FLAG, 0) FEE_DISPUTE_FLAG, COALESCE(ev.CLAIMS_12M, 0) CLAIMS_12M,
  IFF(tx.SALARY_CREDITS_PRIOR > 0 AND tx.SALARY_CREDITS_60D = 0, 1, 0) SALARY_DROP_FLAG,
  ROUND(DIV0NULL(tx.CARD_SPEND_3M, tx.CARD_SPEND_PREV_3M), 3) SPEND_TREND,
  ROUND(DIV0NULL(tx.OUTFLOW_3M, tx.INFLOW_3M), 3) OUTFLOW_RATIO,
  -- Annual relationship value proxy (net interest margin + fee/premium income)
  ROUND(COALESCE(acc.TOTAL_OUTSTANDING, 0) * 0.025 + COALESCE(acc.MONTHLY_OBLIGATION, 0) * 12 * IFF(c.INDUSTRY_TYPE = 'INSURANCE', 0.25, 0.05)
        + DECODE(c.SEGMENT, 'PREMIER', 60000, 'AFFLUENT', 20000, 'SME', 25000, 5000), 0) ANNUAL_VALUE_INR,
  PERCENT_RANK() OVER (ORDER BY ANNUAL_VALUE_INR) VALUE_PERCENTILE
FROM DIM_CUSTOMER c CROSS JOIN cfg
LEFT JOIN acc USING (CUSTOMER_ID) LEFT JOIN pay USING (CUSTOMER_ID) LEFT JOIN inter USING (CUSTOMER_ID)
LEFT JOIN ev USING (CUSTOMER_ID) LEFT JOIN tx USING (CUSTOMER_ID);


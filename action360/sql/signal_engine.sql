-- ---------------------------------------------------------------------
-- CUSTOMER_SIGNAL  (normalised, long format)
-- ---------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE CUSTOMER_SIGNAL
  TARGET_LAG = 'DOWNSTREAM' WAREHOUSE = ACTION360_WH REFRESH_MODE = FULL
  COMMENT = 'Normalised customer signals in [0,1]'
AS
WITH n AS (
  SELECT CUSTOMER_ID,
    GREATEST(0, -COALESCE(AVG_SENTIMENT_90D, 0))::FLOAT NEG_SENTIMENT,
    LEAST(COMPLAINTS_90D, 3) / 3.0::FLOAT COMPLAINTS,
    LEAST(UNRESOLVED_COUNT, 2) / 2.0::FLOAT UNRESOLVED,
    IFF(ESCALATED_COUNT > 0, 1, 0)::FLOAT ESCALATED,
    IFF(DAYS_TO_RENEWAL BETWEEN 0 AND 90, 1 - DAYS_TO_RENEWAL / 90.0, 0)::FLOAT RENEWAL_PROXIMITY,
    LEAST(MISSED_6M, 3) / 3.0::FLOAT MISSED_PAYMENTS,
    LEAST(MAX_DAYS_LATE_90D, 60) / 60.0::FLOAT DAYS_LATE,
    SALARY_DROP_FLAG::FLOAT SALARY_DROP,
    HARDSHIP_MENTION::FLOAT HARDSHIP,
    RESTRUCTURE_FLAG::FLOAT RESTRUCTURE_REQ,
    LEAST(1, GREATEST(0, (750 - CREDIT_SCORE) / 200.0))::FLOAT LOW_CREDIT,
    FORECLOSURE_FLAG::FLOAT FORECLOSURE_INTENT,
    COMPETITOR_MENTION::FLOAT COMPETITOR_MENTION,
    LEAST(1, COALESCE(OUTFLOW_RATIO, 0) * 2)::FLOAT OUTFLOW_OTHER_BANK,
    IFF(TENURE_MONTHS < 12, 1, 0)::FLOAT LOW_TENURE,
    VALUE_PERCENTILE::FLOAT CUSTOMER_VALUE,
    LEAST(INTERACTIONS_90D, 5) / 5.0::FLOAT ENGAGEMENT,
    IFF(DAYS_SINCE_LAST_INTERACTION IS NULL, 0, GREATEST(0, 1 - DAYS_SINCE_LAST_INTERACTION / 90.0))::FLOAT RECENCY,
    IFF(INDUSTRY_TYPE = 'INSURANCE', IFF(HAS_TERM_LIFE = 0, 0.5, 0) + IFF(HAS_HEALTH = 1 AND HAS_FAMILY_FLOATER = 0, 0.5, 0) * IFF(LIFE_EVENT = 1 OR ENDORSEMENT_FLAG = 1, 1, 0.4),
        IFF(SEGMENT IN ('AFFLUENT','PREMIER') AND PRODUCT_COUNT = 1, 0.6, 0))::FLOAT PRODUCT_GAP,
    GREATEST(LIFE_EVENT, ENDORSEMENT_FLAG)::FLOAT LIFE_EVENT,
    LEAST(1, 0.4 * LEAST(1, GREATEST(0, (COALESCE(SPEND_TREND, 1) - 1) * 2.5)) + 0.4 * UPGRADE_INTEREST + 0.2 * IFF(MISSED_6M = 0 AND LATE_6M = 0, 1, 0))::FLOAT UPGRADE_READINESS,
    LEAST(1, GREATEST(0, (CREDIT_SCORE - 550) / 300.0))::FLOAT CREDIT_QUALITY,
    CLAIM_DELAYED_FLAG::FLOAT CLAIM_DELAYED,
    DOC_PENDING_FLAG::FLOAT DOC_PENDING,
    TOPUP_FLAG::FLOAT TOPUP_INTENT
  FROM CUSTOMER_FEATURES),
o AS (SELECT CUSTOMER_ID, OBJECT_CONSTRUCT(*) OBJ FROM n)
SELECT o.CUSTOMER_ID, f.KEY::STRING SIGNAL_NAME, ROUND(f.VALUE::FLOAT, 4) SIGNAL_VALUE, d.DISPLAY_NAME, d.SIGNAL_SOURCE
FROM o, LATERAL FLATTEN(INPUT => o.OBJ) f
-- the join to the governed catalogue keeps only defined signals (drops CUSTOMER_ID)
JOIN SIGNAL_DEFINITION d ON d.SIGNAL_NAME = f.KEY::STRING;

-- ---------------------------------------------------------------------
-- Configurable risk model weights (each model sums to 1.0)
-- ---------------------------------------------------------------------
CREATE OR REPLACE TABLE RISK_MODEL_WEIGHT (RISK_MODEL STRING, SIGNAL_NAME STRING, WEIGHT FLOAT, PRIMARY KEY (RISK_MODEL, SIGNAL_NAME));
INSERT INTO RISK_MODEL_WEIGHT VALUES
 ('CHURN','NEG_SENTIMENT',0.17),('CHURN','COMPLAINTS',0.13),('CHURN','UNRESOLVED',0.12),('CHURN','FORECLOSURE_INTENT',0.14),
 ('CHURN','COMPETITOR_MENTION',0.14),('CHURN','RENEWAL_PROXIMITY',0.10),('CHURN','OUTFLOW_OTHER_BANK',0.08),('CHURN','LOW_TENURE',0.05),('CHURN','ESCALATED',0.07),
 ('PAYMENT','MISSED_PAYMENTS',0.32),('PAYMENT','DAYS_LATE',0.22),('PAYMENT','SALARY_DROP',0.16),('PAYMENT','HARDSHIP',0.12),('PAYMENT','RESTRUCTURE_REQ',0.10),('PAYMENT','LOW_CREDIT',0.08),
 ('SERVICE','UNRESOLVED',0.33),('SERVICE','COMPLAINTS',0.25),('SERVICE','ESCALATED',0.15),('SERVICE','CLAIM_DELAYED',0.15),('SERVICE','NEG_SENTIMENT',0.12);

-- ---------------------------------------------------------------------
-- CUSTOMER_RISK  (scores, tier, explainable drivers, cost-aware AI route)
-- ---------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE CUSTOMER_RISK
  TARGET_LAG = 'DOWNSTREAM' WAREHOUSE = ACTION360_WH REFRESH_MODE = FULL
  COMMENT = 'Churn / payment / service risk with drivers and AI enrichment route'
AS
WITH contrib AS (
  SELECT s.CUSTOMER_ID, w.RISK_MODEL, s.SIGNAL_NAME, s.DISPLAY_NAME, s.SIGNAL_VALUE, w.WEIGHT, s.SIGNAL_VALUE * w.WEIGHT AS CONTRIBUTION
  FROM CUSTOMER_SIGNAL s JOIN RISK_MODEL_WEIGHT w ON w.SIGNAL_NAME = s.SIGNAL_NAME),
agg AS (
  SELECT CUSTOMER_ID,
    ROUND(SUM(IFF(RISK_MODEL = 'CHURN', CONTRIBUTION, 0)), 4) CHURN_RISK,
    ROUND(SUM(IFF(RISK_MODEL = 'PAYMENT', CONTRIBUTION, 0)), 4) PAYMENT_RISK,
    ROUND(SUM(IFF(RISK_MODEL = 'SERVICE', CONTRIBUTION, 0)), 4) SERVICE_RISK
  FROM contrib GROUP BY 1),
-- Opportunity (growth) score: upgrade readiness or a coverage gap backed by a life event
opp AS (
  SELECT CUSTOMER_ID, ROUND(GREATEST(MAX(IFF(SIGNAL_NAME = 'UPGRADE_READINESS', SIGNAL_VALUE, 0)),
         (MAX(IFF(SIGNAL_NAME = 'PRODUCT_GAP', SIGNAL_VALUE, 0)) + MAX(IFF(SIGNAL_NAME = 'LIFE_EVENT', SIGNAL_VALUE, 0))) / 2), 4) OPPORTUNITY_SCORE
  FROM CUSTOMER_SIGNAL GROUP BY 1),
drv AS (
  SELECT CUSTOMER_ID,
    ARRAY_AGG(OBJECT_CONSTRUCT('signal', SIGNAL_NAME, 'label', DISPLAY_NAME, 'model', RISK_MODEL, 'value', SIGNAL_VALUE, 'contribution', ROUND(CONTRIBUTION, 4)))
      WITHIN GROUP (ORDER BY CONTRIBUTION DESC) ALL_DRIVERS
  FROM (SELECT * FROM contrib WHERE CONTRIBUTION > 0
        QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID, SIGNAL_NAME ORDER BY CONTRIBUTION DESC) = 1)
  GROUP BY 1),
th AS (SELECT MAX(IFF(CONFIG_KEY = 'LLM_ENRICHMENT_THRESHOLD', TRY_TO_DOUBLE(CONFIG_VALUE), NULL)) FULL_T,
              MAX(IFF(CONFIG_KEY = 'SELECTIVE_ENRICHMENT_THRESHOLD', TRY_TO_DOUBLE(CONFIG_VALUE), NULL)) SEL_T FROM APP_CONFIG)
SELECT a.CUSTOMER_ID, a.CHURN_RISK, a.PAYMENT_RISK, a.SERVICE_RISK, opp.OPPORTUNITY_SCORE,
  GREATEST(a.CHURN_RISK, a.PAYMENT_RISK, a.SERVICE_RISK) RISK_SCORE,
  CASE GREATEST(a.CHURN_RISK, a.PAYMENT_RISK, a.SERVICE_RISK) WHEN a.CHURN_RISK THEN 'CHURN' WHEN a.PAYMENT_RISK THEN 'PAYMENT' ELSE 'SERVICE' END PRIMARY_RISK_TYPE,
  CASE WHEN GREATEST(a.CHURN_RISK, a.PAYMENT_RISK, a.SERVICE_RISK) >= th.FULL_T THEN 'HIGH'
       WHEN GREATEST(a.CHURN_RISK, a.PAYMENT_RISK, a.SERVICE_RISK) >= th.SEL_T THEN 'MEDIUM' ELSE 'LOW' END RISK_TIER,
  CASE WHEN GREATEST(a.CHURN_RISK, a.PAYMENT_RISK, a.SERVICE_RISK) >= th.FULL_T THEN 'FULL_AGENT'
       WHEN GREATEST(a.CHURN_RISK, a.PAYMENT_RISK, a.SERVICE_RISK) >= th.SEL_T OR opp.OPPORTUNITY_SCORE >= 0.6 THEN 'SELECTIVE_AI' ELSE 'RULES_ONLY' END AI_ROUTE,
  ARRAY_SLICE(COALESCE(d.ALL_DRIVERS, []), 0, 3) TOP_DRIVERS
FROM agg a CROSS JOIN th LEFT JOIN drv d USING (CUSTOMER_ID) LEFT JOIN opp USING (CUSTOMER_ID);

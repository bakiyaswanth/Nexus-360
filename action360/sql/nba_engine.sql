-- ---------------------------------------------------------------------
-- OFFER_ELIGIBILITY  (every rule evaluated, every outcome explainable)
-- ---------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE OFFER_ELIGIBILITY
  TARGET_LAG = 'DOWNSTREAM' WAREHOUSE = ACTION360_WH REFRESH_MODE = FULL
  COMMENT = 'Deterministic rule evaluation per customer x offer'
AS
WITH attr AS (
  SELECT f.CUSTOMER_ID, f.INDUSTRY_TYPE, f.SEGMENT,
    OBJECT_CONSTRUCT(
      'TENURE_MONTHS', f.TENURE_MONTHS::FLOAT, 'CREDIT_SCORE', f.CREDIT_SCORE::FLOAT, 'AGE', f.AGE::FLOAT,
      'MISSED_6M', f.MISSED_6M::FLOAT, 'LATE_6M', f.LATE_6M::FLOAT, 'MAX_DAYS_LATE_90D', f.MAX_DAYS_LATE_90D::FLOAT,
      'DAYS_TO_RENEWAL', f.DAYS_TO_RENEWAL::FLOAT, 'CLAIMS_12M', f.CLAIMS_12M::FLOAT, 'SPEND_TREND', COALESCE(f.SPEND_TREND, 0)::FLOAT,
      'COMPLAINTS_90D', f.COMPLAINTS_90D::FLOAT, 'UNRESOLVED_COUNT', f.UNRESOLVED_COUNT::FLOAT, 'RESTRUCTURE_FLAG', f.RESTRUCTURE_FLAG::FLOAT,
      'HAS_CC', f.HAS_CC::FLOAT, 'HAS_HEALTH', f.HAS_HEALTH::FLOAT, 'HAS_FAMILY_FLOATER', f.HAS_FAMILY_FLOATER::FLOAT,
      'HAS_TERM_LIFE', f.HAS_TERM_LIFE::FLOAT, 'HAS_MOTOR', f.HAS_MOTOR::FLOAT,
      'HOLDS_HL_OR_PL', GREATEST(f.HAS_HL, f.HAS_PL)::FLOAT,
      'PAYMENT_DISTRESS', IFF(f.MISSED_6M >= 1 OR f.MAX_DAYS_LATE_90D >= 15, 1, 0)::FLOAT,
      'CHURN_RISK', r.CHURN_RISK::FLOAT) NUM
  FROM CUSTOMER_FEATURES f JOIN CUSTOMER_RISK r USING (CUSTOMER_ID)),
ev AS (
  SELECT a.CUSTOMER_ID, o.OFFER_ID, o.OFFER_NAME, o.OFFER_CATEGORY, o.PRIORITY, o.POLICY_DOC_ID, r.RULE_ID, r.RULE_DESCRIPTION,
    CASE WHEN r.ATTRIBUTE = 'SEGMENT' THEN a.SEGMENT ELSE TO_VARCHAR(a.NUM[r.ATTRIBUTE]) END ACTUAL_VALUE,
    COALESCE(CASE r.OPERATOR
      WHEN '>=' THEN a.NUM[r.ATTRIBUTE]::FLOAT >= r.THRESHOLD_NUM
      WHEN '<=' THEN a.NUM[r.ATTRIBUTE]::FLOAT <= r.THRESHOLD_NUM
      WHEN '='  THEN a.NUM[r.ATTRIBUTE]::FLOAT = r.THRESHOLD_NUM
      WHEN 'IN' THEN ARRAY_CONTAINS(a.SEGMENT::VARIANT, SPLIT(r.THRESHOLD_TEXT, ','))
    END, FALSE) AS PASSED
  FROM attr a
  JOIN OFFER_CATALOG o ON o.IS_ACTIVE AND o.INDUSTRY_TYPE IN (a.INDUSTRY_TYPE, 'ALL')
  JOIN OFFER_ELIGIBILITY_RULE r ON r.OFFER_ID = o.OFFER_ID AND r.IS_HARD)
SELECT CUSTOMER_ID, OFFER_ID, ANY_VALUE(OFFER_NAME) OFFER_NAME, ANY_VALUE(OFFER_CATEGORY) OFFER_CATEGORY,
  ANY_VALUE(PRIORITY) PRIORITY, ANY_VALUE(POLICY_DOC_ID) POLICY_DOC_ID,
  BOOLAND_AGG(PASSED) IS_ELIGIBLE,
  ARRAY_AGG(IFF(PASSED, NULL, RULE_DESCRIPTION || ' (actual: ' || COALESCE(ACTUAL_VALUE, 'n/a') || ')')) FAILED_RULES,
  ARRAY_AGG(IFF(PASSED, RULE_DESCRIPTION, NULL)) PASSED_RULES,
  COUNT(*) RULES_EVALUATED
FROM ev GROUP BY CUSTOMER_ID, OFFER_ID;


-- ---------------------------------------------------------------------
-- NBA_CANDIDATE  (all candidates, scored, gated and ranked)
-- ---------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE NBA_CANDIDATE
  TARGET_LAG = 'DOWNSTREAM' WAREHOUSE = ACTION360_WH REFRESH_MODE = FULL
  COMMENT = 'Candidate next-best-actions with transparent score, guardrails and eligibility'
AS
WITH risk_sig AS (
  SELECT r.CUSTOMER_ID, f.KEY::STRING SIGNAL_NAME, f.VALUE::FLOAT SIGNAL_VALUE
  FROM CUSTOMER_RISK r, LATERAL FLATTEN(INPUT => OBJECT_CONSTRUCT('CHURN_RISK', r.CHURN_RISK, 'PAYMENT_RISK', r.PAYMENT_RISK,
                                                               'SERVICE_RISK', r.SERVICE_RISK, 'OPPORTUNITY_SCORE', r.OPPORTUNITY_SCORE)) f),
sig AS (SELECT CUSTOMER_ID, SIGNAL_NAME, SIGNAL_VALUE FROM CUSTOMER_SIGNAL UNION ALL SELECT * FROM risk_sig),
cand AS (
  SELECT f.CUSTOMER_ID, f.INDUSTRY_TYPE, a.*
  FROM CUSTOMER_FEATURES f JOIN ACTION_CATALOG a ON a.INDUSTRY_SCOPE IN ('ALL', f.INDUSTRY_TYPE)),
scored AS (
  SELECT c.CUSTOMER_ID, c.ACTION_CODE,
    ANY_VALUE(c.BASE_SCORE) + COALESCE(SUM(w.WEIGHT * s.SIGNAL_VALUE), 0) SCORE,
    ARRAY_AGG(IFF(w.WEIGHT * s.SIGNAL_VALUE <> 0, OBJECT_CONSTRUCT('signal', w.SIGNAL_NAME, 'weight', w.WEIGHT, 'value', s.SIGNAL_VALUE,
              'contribution', ROUND(w.WEIGHT * s.SIGNAL_VALUE, 4)), NULL)) WITHIN GROUP (ORDER BY ABS(w.WEIGHT * s.SIGNAL_VALUE) DESC) CONTRIBUTIONS
  FROM cand c LEFT JOIN NBA_WEIGHT w ON w.ACTION_CODE = c.ACTION_CODE
  LEFT JOIN sig s ON s.CUSTOMER_ID = c.CUSTOMER_ID AND s.SIGNAL_NAME = w.SIGNAL_NAME
  GROUP BY 1, 2),
guard AS (
  SELECT c.CUSTOMER_ID, c.ACTION_CODE, ARRAY_AGG(g.REASON) BLOCK_REASONS
  FROM cand c JOIN NBA_GUARDRAIL g ON g.ACTION_CODE = c.ACTION_CODE
  JOIN sig s ON s.CUSTOMER_ID = c.CUSTOMER_ID AND s.SIGNAL_NAME = g.SIGNAL_NAME
  WHERE CASE g.OPERATOR WHEN '>=' THEN s.SIGNAL_VALUE >= g.THRESHOLD WHEN '<' THEN s.SIGNAL_VALUE < g.THRESHOLD
                        WHEN '<=' THEN s.SIGNAL_VALUE <= g.THRESHOLD WHEN '>' THEN s.SIGNAL_VALUE > g.THRESHOLD END
  GROUP BY 1, 2),
offer AS (
  SELECT c.CUSTOMER_ID, c.ACTION_CODE,
    ARRAY_AGG(IFF(e.IS_ELIGIBLE, OBJECT_CONSTRUCT('offer_id', e.OFFER_ID, 'offer_name', e.OFFER_NAME, 'policy_doc', e.POLICY_DOC_ID,
              'passed_rules', e.PASSED_RULES), NULL)) WITHIN GROUP (ORDER BY e.PRIORITY DESC) ELIGIBLE_OFFERS,
    ARRAY_AGG(IFF(NOT e.IS_ELIGIBLE, OBJECT_CONSTRUCT('offer_id', e.OFFER_ID, 'offer_name', e.OFFER_NAME, 'failed_rules', e.FAILED_RULES), NULL))
      WITHIN GROUP (ORDER BY e.PRIORITY DESC) INELIGIBLE_OFFERS
  FROM cand c JOIN OFFER_ELIGIBILITY e ON e.CUSTOMER_ID = c.CUSTOMER_ID AND e.OFFER_CATEGORY = c.OFFER_CATEGORY
  GROUP BY 1, 2),
j AS (
  SELECT c.CUSTOMER_ID, c.ACTION_CODE, c.ACTION_NAME, c.OFFER_CATEGORY, c.OFFER_MODE, c.BUSINESS_PURPOSE, c.OWNER_ROLE, c.DEFAULT_CHANNEL,
    ROUND(s.SCORE, 4) ACTION_SCORE, ARRAY_SLICE(s.CONTRIBUTIONS, 0, 4) TOP_CONTRIBUTIONS,
    COALESCE(g.BLOCK_REASONS, []) BLOCK_REASONS,
    o.ELIGIBLE_OFFERS[0] SELECTED_OFFER, COALESCE(o.INELIGIBLE_OFFERS, []) INELIGIBLE_OFFERS,
    CASE WHEN ARRAY_SIZE(COALESCE(g.BLOCK_REASONS, [])) > 0 THEN 'BLOCKED_GUARDRAIL'
         WHEN c.OFFER_MODE = 'REQUIRED' AND o.ELIGIBLE_OFFERS[0] IS NULL THEN 'NOT_ELIGIBLE'
         WHEN c.ACTION_CODE <> 'NO_ACTION_MONITOR' AND s.SCORE < m.MIN_SCORE THEN 'BELOW_THRESHOLD'
         ELSE 'ELIGIBLE' END CANDIDATE_STATUS
  FROM cand c JOIN scored s USING (CUSTOMER_ID, ACTION_CODE)
  CROSS JOIN (SELECT COALESCE(MAX(IFF(CONFIG_KEY = 'MIN_ACTION_SCORE', TRY_TO_DOUBLE(CONFIG_VALUE), NULL)), 0.40) MIN_SCORE FROM APP_CONFIG) m
  LEFT JOIN guard g USING (CUSTOMER_ID, ACTION_CODE) LEFT JOIN offer o USING (CUSTOMER_ID, ACTION_CODE))
SELECT j.*,
  IFF(CANDIDATE_STATUS = 'ELIGIBLE', ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID, CANDIDATE_STATUS = 'ELIGIBLE' ORDER BY ACTION_SCORE DESC, ACTION_CODE), NULL) ELIGIBLE_RANK
FROM j;

-- ---------------------------------------------------------------------
-- CUSTOMER_360  (one row per customer; the single source for UI + agent)
-- ---------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE CUSTOMER_360
  TARGET_LAG = '12 hours' WAREHOUSE = ACTION360_WH REFRESH_MODE = FULL
  COMMENT = 'Unified Customer 360: identity, financial, interaction, risk, AI context and recommended action'
AS
WITH top2 AS (
  SELECT CUSTOMER_ID,
    MAX(IFF(ELIGIBLE_RANK = 1, ACTION_CODE, NULL)) RECOMMENDED_ACTION,
    MAX(IFF(ELIGIBLE_RANK = 1, ACTION_NAME, NULL)) RECOMMENDED_ACTION_NAME,
    MAX(IFF(ELIGIBLE_RANK = 1, ACTION_SCORE, NULL)) RECOMMENDED_ACTION_SCORE,
    MAX(IFF(ELIGIBLE_RANK = 1, SELECTED_OFFER:offer_id::STRING, NULL)) RECOMMENDED_OFFER_ID,
    MAX(IFF(ELIGIBLE_RANK = 2, ACTION_CODE, NULL)) SECONDARY_ACTION,
    MAX(IFF(ELIGIBLE_RANK = 2, ACTION_SCORE, NULL)) SECONDARY_ACTION_SCORE,
    COUNT_IF(CANDIDATE_STATUS = 'ELIGIBLE' AND ACTION_CODE <> 'NO_ACTION_MONITOR') ELIGIBLE_ACTION_COUNT
  FROM NBA_CANDIDATE GROUP BY 1),
latest AS (
  SELECT i.CUSTOMER_ID,
    ARRAY_AGG(OBJECT_CONSTRUCT('ts', i.INTERACTION_TS, 'channel', i.CHANNEL, 'topic', i.TOPIC, 'note', i.NOTE))
      WITHIN GROUP (ORDER BY COALESCE(t.AI_SENTIMENT_SCORE, i.RULE_SENTIMENT), i.INTERACTION_TS DESC)[0] LATEST_IMPORTANT_INTERACTION
  FROM FACT_INTERACTION i LEFT JOIN CALL_TRANSCRIPT t USING (INTERACTION_ID)
  WHERE i.INTERACTION_TS >= DATEADD(day, -120, '2026-10-02'::DATE)
  GROUP BY 1)
SELECT f.CUSTOMER_ID, f.FULL_NAME, f.SEGMENT, f.INDUSTRY_TYPE, f.AGE, f.CITY, f.TENURE_MONTHS, f.PREFERRED_CHANNEL, f.CREDIT_SCORE,
  f.PRODUCT_COUNT, f.PRODUCTS, f.TOTAL_OUTSTANDING, f.TOTAL_EXPOSURE_OR_COVER, f.MONTHLY_OBLIGATION, f.OVERDUE_AMOUNT,
  f.PAYMENT_STATUS, f.MISSED_6M, f.LATE_6M, f.MAX_DAYS_LATE_90D, f.ON_TIME_RATE_12M,
  f.NEXT_RENEWAL_DATE, f.NEXT_RENEWAL_PRODUCT, f.DAYS_TO_RENEWAL, f.ANNUAL_VALUE_INR, ROUND(f.VALUE_PERCENTILE, 3) VALUE_PERCENTILE,
  f.TOTAL_INTERACTIONS, f.INTERACTIONS_90D, f.COMPLAINTS_90D, f.UNRESOLVED_COUNT, f.OPEN_REQUESTS, f.ESCALATED_COUNT, f.NEGATIVE_INTERACTIONS_90D,
  f.AVG_SENTIMENT_90D, f.LATEST_SENTIMENT,
  CASE WHEN f.AVG_SENTIMENT_90D IS NULL THEN 'NO RECENT CONTACT' WHEN f.AVG_SENTIMENT_90D <= -0.3 THEN 'NEGATIVE'
       WHEN f.AVG_SENTIMENT_90D < 0.1 THEN 'NEUTRAL' ELSE 'POSITIVE' END SENTIMENT_LABEL,
  f.DOMINANT_TOPIC, f.LAST_INTERACTION_TS, f.DAYS_SINCE_LAST_INTERACTION,
  f.COMPETITOR_MENTION, f.LIFE_EVENT, f.HARDSHIP_MENTION, f.FORECLOSURE_FLAG, f.CLAIM_DELAYED_FLAG, f.CLAIMS_12M,
  r.CHURN_RISK, r.PAYMENT_RISK, r.SERVICE_RISK, r.OPPORTUNITY_SCORE, r.RISK_SCORE, r.RISK_TIER, r.PRIMARY_RISK_TYPE, r.AI_ROUTE, r.TOP_DRIVERS,
  t.RECOMMENDED_ACTION, t.RECOMMENDED_ACTION_NAME, t.RECOMMENDED_ACTION_SCORE, t.RECOMMENDED_OFFER_ID,
  t.SECONDARY_ACTION, t.SECONDARY_ACTION_SCORE, t.ELIGIBLE_ACTION_COUNT,
  IFF(t.RECOMMENDED_ACTION <> 'NO_ACTION_MONITOR', TRUE, FALSE) NEEDS_ACTION,
  ai.CUSTOMER_NEED, ai.KEY_DRIVERS AI_KEY_DRIVERS, ai.PAIN_POINTS AI_PAIN_POINTS, ai.GENERATED_AT AI_GENERATED_AT,
  l.LATEST_IMPORTANT_INTERACTION
FROM CUSTOMER_FEATURES f
JOIN CUSTOMER_RISK r USING (CUSTOMER_ID)
LEFT JOIN top2 t USING (CUSTOMER_ID)
LEFT JOIN CUSTOMER_AI_INSIGHT ai USING (CUSTOMER_ID)
LEFT JOIN latest l USING (CUSTOMER_ID);


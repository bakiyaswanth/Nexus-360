CREATE TABLE IF NOT EXISTS NBA_RECOMMENDATION (
  RECOMMENDATION_ID STRING DEFAULT UUID_STRING() PRIMARY KEY, CUSTOMER_ID STRING, QUESTION STRING,
  SELECTED_ACTION STRING, CANDIDATE_ACTIONS VARIANT, ACTION_SCORE FLOAT, REASONS VARIANT, SUPPORTING_EVIDENCE VARIANT,
  OFFER_ID STRING, ELIGIBILITY_RESULT VARIANT, CONFIDENCE STRING, AI_ROUTE STRING, GENERATED_EXPLANATION STRING,
  GENERATED_MESSAGE STRING, MODEL STRING, LATENCY_MS INT, CREATED_BY STRING DEFAULT CURRENT_USER(),
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());

CREATE TABLE IF NOT EXISTS ACTION_AUDIT (
  AUDIT_ID STRING DEFAULT UUID_STRING() PRIMARY KEY, RECOMMENDATION_ID STRING, CUSTOMER_ID STRING, QUESTION STRING,
  RECOMMENDATION STRING, RECOMMENDATION_REASON STRING, OFFER_ID STRING, ELIGIBILITY_STATUS STRING, EVIDENCE_REFERENCES VARIANT,
  USER_ACTION STRING, OUTREACH_MESSAGE STRING, EXECUTION_MODE STRING DEFAULT 'SIMULATED', DOWNSTREAM_STATUS STRING,
  ACTED_BY STRING DEFAULT CURRENT_USER(), ACTED_ROLE STRING DEFAULT CURRENT_ROLE(),
  ACTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), PREV_HASH STRING, RECORD_HASH STRING)
  CHANGE_TRACKING = TRUE
  COMMENT = 'Append-only audit. Writes only via CORE.LOG_ACTION; hash chain makes tampering detectable';

CREATE TABLE IF NOT EXISTS AI_USAGE_METRICS (
  EVENT_ID STRING DEFAULT UUID_STRING(), EVENT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), COMPONENT STRING,
  CUSTOMER_ID STRING, AI_ROUTE STRING, AI_FUNCTION STRING, MODEL STRING, CALLS INT, EST_TOKENS INT, LATENCY_MS INT,
  SKIPPED BOOLEAN DEFAULT FALSE, DETAILS VARIANT);

CREATE TABLE IF NOT EXISTS EVALUATION_CASE (
  CASE_ID STRING PRIMARY KEY, SCENARIO STRING, CUSTOMER_ID STRING, QUESTION STRING, EXPECTED_ACTION STRING,
  EXPECTED_OFFER_ID STRING, EXPECTED_ELIGIBILITY STRING, FORBIDDEN_OFFER_ID STRING, EXPECTED_ROUTE STRING,
  MUST_CITE STRING, IS_NEGATIVE BOOLEAN);
